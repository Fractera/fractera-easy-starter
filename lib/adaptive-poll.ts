// Адаптивный опрос хода установки: 5 секунд первую минуту, дальше 30.
//
// 🔒 ПОЧЕМУ ДВЕ СКОРОСТИ, А НЕ ОДНА (решение владельца 2026-08-20).
//
// Пять секунд ввели 17 августа (`0eab9a2`, «два письма, адрес сразу на сайте»):
// именно этот опрос оживляет блок адресов и зажигает тост успеха, поэтому при
// 30 секундах клиент мог полминуты сидеть перед готовым сервером, которому
// говорят «ещё устанавливается». Плата оказалась шестикратной: установка идёт
// 10–20 минут, и всё это время вкладка спрашивала сервер каждые пять секунд —
// притом что середина установки не меняется вовсе.
//
// Быстро нужно ровно там, где что-то происходит на глазах: первая минута, когда
// появляются IP и адреса. Дальше цена перевешивает пользу, и шаг возвращается к
// прежним 30 секундам.
//
// Попутно чинится давняя мелочь `setInterval`: он ставит вызовы в очередь, не
// дожидаясь ответа, и на медленной сети опросы наслаиваются друг на друга.
// Цепочка `setTimeout` ждёт завершения предыдущего — запрос всегда один.
export function startAdaptivePoll(
  tick: () => void | Promise<void>,
  opts: { fastMs?: number; slowMs?: number; fastWindowMs?: number } = {},
): () => void {
  const fastMs = opts.fastMs ?? 5_000
  const slowMs = opts.slowMs ?? 30_000
  const fastWindowMs = opts.fastWindowMs ?? 60_000

  const startedAt = Date.now()
  let timer: ReturnType<typeof setTimeout> | null = null
  let stopped = false

  // Возвращаемая остановка зовётся из двух мест: разбор компонента и сам `tick`,
  // когда установка закончилась или упала. Флаг нужен потому, что остановка
  // может прийти ПОКА выполняется запрос — без него следующий шаг встал бы в
  // очередь уже после неё.
  const stop = () => {
    stopped = true
    if (timer) clearTimeout(timer)
    timer = null
  }

  const schedule = () => {
    if (stopped) return
    const delay = Date.now() - startedAt < fastWindowMs ? fastMs : slowMs
    timer = setTimeout(async () => {
      await tick()
      schedule()
    }, delay)
  }

  schedule()
  return stop
}
